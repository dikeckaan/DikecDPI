def ios_string(value, order):
    s = value.replace("%", "%%")
    for n in re.findall(r"\{(\w+)\}", value):
        idx = order.index(n) + 1 if n in order else 1
        s = s.replace("{%s}" % n, "%%%d$@" % idx)
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    catalog = android_gen.parse_catalog(open(android_gen.SRC, encoding="utf-8").read())
    for lang in LPROJ:
        catalog.setdefault(lang, {}).update(IOS.get(lang, {}))
    english = catalog["en"]
    orders = {k: re.findall(r"\{(\w+)\}", v) for k, v in english.items()}
    for lang, folder in LPROJ.items():
        entries = dict(english)  # fall back to English for missing keys
        entries.update(catalog.get(lang, {}))
        lines = ["/* Generated by ios/tools/gen_strings.py from gui/frontend/i18n.js. Do not edit. */"]
        for key in sorted(entries):
            lines.append('"%s" = "%s";' % (key, ios_string(entries[key], orders.get(key, []))))
        d = os.path.join(OUT, folder + ".lproj")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "Localizable.strings"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        print(f"{folder:8} {len(entries)} strings")


if __name__ == "__main__":
    main()
